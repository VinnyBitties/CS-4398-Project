"use strict";

/**
 * The database: the team's PostgreSQL server (Azure) when DATABASE_URL is
 * set, otherwise a local SQLite file. Both sit behind the same small async
 * API, so the stores never know which one they are talking to:
 *
 *   await db.get(sql, params)     -> first row, or null
 *   await db.all(sql, params)     -> array of rows
 *   await db.run(sql, params)     -> { changes }
 *   await db.insert(sql, params)  -> id of the new row
 *   await db.transaction(async (tx) => { ... })   tx has the same methods
 *
 * SQL is written once, with `?` placeholders, in the subset both databases
 * understand. Timestamps are ISO 8601 UTC strings on the way out of either
 * database, so API responses look the same whichever one is in use.
 */

const fs = require("node:fs");
const path = require("node:path");
const config = require("./config");

// ---- schemas -----------------------------------------------------------------
// Same tables and columns; only the type syntax differs.

const POSTGRES_SCHEMA = `
  -- Dashboard accounts. Passwords are never stored: password_hash is a
  -- self-describing scrypt string (see src/auth/passwords.js).
  CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_login_at TIMESTAMPTZ
  );
  CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username ON users (lower(username));

  -- One row per signed-in browser. The cookie holds a random token; only its
  -- SHA-256 is stored, so a copy of the database cannot be used to log in.
  CREATE TABLE IF NOT EXISTS sessions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash TEXT NOT NULL UNIQUE,
    user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL
  );
  CREATE INDEX IF NOT EXISTS idx_sessions_user_id ON sessions (user_id);

  CREATE TABLE IF NOT EXISTS samples (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sha256 TEXT NOT NULL,             -- file contents, or the normalized URL for a link
    submission_type TEXT NOT NULL CHECK (submission_type IN ('file', 'link')),
    original_filename TEXT,
    submitted_url TEXT,
    file_size BIGINT,
    stored_path TEXT,                 -- where the upload lives, on the disk of the backend that received it
    user_id INTEGER REFERENCES users (id) ON DELETE SET NULL, -- NULL = submitted without signing in
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
  );
  CREATE INDEX IF NOT EXISTS idx_samples_sha256 ON samples (sha256);
  CREATE INDEX IF NOT EXISTS idx_samples_user_id ON samples (user_id, id);

  CREATE TABLE IF NOT EXISTS results (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sample_id INTEGER NOT NULL REFERENCES samples (id) ON DELETE CASCADE,
    stage TEXT NOT NULL,              -- 'signature' | 'static_analysis' | 'static_ml' | 'sandbox' | 'behavioral_ml' | 'llm'
    status TEXT NOT NULL,             -- 'running' | 'complete' | 'failed'
    signature_match SMALLINT,         -- 0/1, only meaningful for stage = 'signature'
    report_json JSONB,                -- full stage report; JSONB so reports can be queried in SQL
    error_message TEXT,               -- JSON-encoded { code, message, details } when status = 'failed'
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
  );
  CREATE INDEX IF NOT EXISTS idx_results_sample_id ON results (sample_id);

  -- One job per submission: the unit of work the queue hands to a worker.
  CREATE TABLE IF NOT EXISTS jobs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sample_id INTEGER NOT NULL REFERENCES samples (id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'queued'
      CHECK (status IN ('queued', 'running', 'completed', 'failed')),
    worker_id TEXT,                   -- the backend that stored the upload and runs this job
    attempts INTEGER NOT NULL DEFAULT 0,
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ
  );
  CREATE INDEX IF NOT EXISTS idx_jobs_worker_status ON jobs (worker_id, status, id);
  CREATE INDEX IF NOT EXISTS idx_jobs_sample_id ON jobs (sample_id);
`;

const NOW_SQLITE = "(strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))";

const SQLITE_SCHEMA = `
  CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    username TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT ${NOW_SQLITE},
    last_login_at TEXT
  );
  CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username ON users (lower(username));

  CREATE TABLE IF NOT EXISTS sessions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    token_hash TEXT NOT NULL UNIQUE,
    user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TEXT NOT NULL DEFAULT ${NOW_SQLITE},
    expires_at TEXT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS idx_sessions_user_id ON sessions (user_id);

  CREATE TABLE IF NOT EXISTS samples (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    sha256 TEXT NOT NULL,
    submission_type TEXT NOT NULL CHECK (submission_type IN ('file', 'link')),
    original_filename TEXT,
    submitted_url TEXT,
    file_size INTEGER,
    stored_path TEXT,
    user_id INTEGER REFERENCES users (id) ON DELETE SET NULL,
    created_at TEXT NOT NULL DEFAULT ${NOW_SQLITE}
  );
  CREATE INDEX IF NOT EXISTS idx_samples_sha256 ON samples (sha256);

  CREATE TABLE IF NOT EXISTS results (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    sample_id INTEGER NOT NULL REFERENCES samples (id) ON DELETE CASCADE,
    stage TEXT NOT NULL,
    status TEXT NOT NULL,
    signature_match INTEGER,
    report_json TEXT,
    error_message TEXT,
    created_at TEXT NOT NULL DEFAULT ${NOW_SQLITE}
  );
  CREATE INDEX IF NOT EXISTS idx_results_sample_id ON results (sample_id);

  CREATE TABLE IF NOT EXISTS jobs (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    sample_id INTEGER NOT NULL REFERENCES samples (id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'queued'
      CHECK (status IN ('queued', 'running', 'completed', 'failed')),
    worker_id TEXT,
    attempts INTEGER NOT NULL DEFAULT 0,
    error_message TEXT,
    created_at TEXT NOT NULL DEFAULT ${NOW_SQLITE},
    started_at TEXT,
    finished_at TEXT
  );
  CREATE INDEX IF NOT EXISTS idx_jobs_sample_id ON jobs (sample_id);
`;

// Local databases created by earlier versions of this backend are missing
// columns that CREATE TABLE IF NOT EXISTS will not add.
function migrateSqlite(sqlite) {
  const columns = (table) => sqlite.prepare(`PRAGMA table_info(${table})`).all().map((c) => c.name);
  const sampleColumns = columns("samples");
  if (!sampleColumns.includes("stored_path")) sqlite.exec("ALTER TABLE samples ADD COLUMN stored_path TEXT");
  if (!sampleColumns.includes("user_id")) {
    // Scans from before accounts existed become guest scans.
    sqlite.exec("ALTER TABLE samples ADD COLUMN user_id INTEGER REFERENCES users (id) ON DELETE SET NULL");
  }
  if (!columns("jobs").includes("worker_id")) sqlite.exec("ALTER TABLE jobs ADD COLUMN worker_id TEXT");
  sqlite.exec("CREATE INDEX IF NOT EXISTS idx_samples_user_id ON samples (user_id, id)");
  sqlite.exec("CREATE INDEX IF NOT EXISTS idx_jobs_worker_status ON jobs (worker_id, status, id)");
}

// ---- SQLite ------------------------------------------------------------------

function createSqlite() {
  const Database = require("better-sqlite3");
  if (config.databasePath !== ":memory:") {
    fs.mkdirSync(path.dirname(config.databasePath), { recursive: true });
  }
  const sqlite = new Database(config.databasePath);
  sqlite.pragma("journal_mode = WAL");
  sqlite.pragma("foreign_keys = ON");
  sqlite.exec(SQLITE_SCHEMA);
  migrateSqlite(sqlite);

  const cache = new Map();
  const prepare = (sql) => {
    let stmt = cache.get(sql);
    if (!stmt) {
      stmt = sqlite.prepare(sql);
      cache.set(sql, stmt);
    }
    return stmt;
  };

  const api = {
    async get(sql, params = []) {
      return prepare(sql).get(...params) || null;
    },
    async all(sql, params = []) {
      return prepare(sql).all(...params);
    },
    async run(sql, params = []) {
      return { changes: prepare(sql).run(...params).changes };
    },
    async insert(sql, params = []) {
      return Number(prepare(sql).run(...params).lastInsertRowid);
    },
  };

  // better-sqlite3 is synchronous, so a transaction only has to stop two
  // async transactions from overlapping; queue them one after another.
  let txChain = Promise.resolve();
  async function transaction(fn) {
    const turn = txChain.then(async () => {
      sqlite.exec("BEGIN IMMEDIATE");
      try {
        const out = await fn(api);
        sqlite.exec("COMMIT");
        return out;
      } catch (err) {
        sqlite.exec("ROLLBACK");
        throw err;
      }
    });
    txChain = turn.catch(() => {});
    return turn;
  }

  return {
    dialect: "sqlite",
    ...api,
    transaction,
    isUniqueViolation: (err) => Boolean(err) && err.code === "SQLITE_CONSTRAINT_UNIQUE",
    ready: Promise.resolve(),
    async close() {
      sqlite.close();
    },
    raw: sqlite,
  };
}

// ---- PostgreSQL --------------------------------------------------------------

// `?` -> `$1, $2, ...`. The queries in this codebase never contain a literal
// question mark, so a plain replace is enough.
function toPgParams(sql) {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
}

function createPostgres() {
  const pg = require("pg");

  // Return timestamps as ISO strings (the API's format) instead of Dates.
  const parseTimestamptz = pg.types.getTypeParser(1184);
  pg.types.setTypeParser(1184, (v) => (v === null ? null : parseTimestamptz(v).toISOString()));

  // A connection string copied from the Azure portal ends in ?sslmode=require,
  // which the pg driver would let override the TLS settings below. Take it
  // out and let DATABASE_SSL decide (sslmode=disable still turns TLS off).
  let connectionString = config.databaseUrl;
  let useSsl = config.databaseSsl;
  try {
    const url = new URL(connectionString);
    const mode = url.searchParams.get("sslmode");
    if (mode) {
      if (mode === "disable") useSsl = false;
      url.searchParams.delete("sslmode");
      connectionString = url.toString();
    }
  } catch (_) {
    /* not a URL; hand it to pg unchanged */
  }

  const pool = new pg.Pool({
    connectionString,
    // Verify the server's certificate; Azure's chains to a root Node trusts.
    ssl: useSsl ? { rejectUnauthorized: true } : false,
    max: config.databasePoolSize,
    idleTimeoutMillis: 30000,
    connectionTimeoutMillis: 15000,
    allowExitOnIdle: true,
  });
  // An idle connection dropped by the server (Azure restarts, network blips)
  // must not crash the backend; the pool replaces it on the next query.
  pool.on("error", (err) => console.error("PostgreSQL connection error:", err.message));

  function bind(client) {
    return {
      async get(sql, params = []) {
        const res = await client.query(toPgParams(sql), params);
        return res.rows[0] || null;
      },
      async all(sql, params = []) {
        return (await client.query(toPgParams(sql), params)).rows;
      },
      async run(sql, params = []) {
        return { changes: (await client.query(toPgParams(sql), params)).rowCount };
      },
      async insert(sql, params = []) {
        const res = await client.query(`${toPgParams(sql)} RETURNING id`, params);
        return Number(res.rows[0].id);
      },
    };
  }

  // Create the tables once. Several teammates' backends may start at the same
  // moment, so serialize on an advisory lock.
  const ready = (async () => {
    const client = await pool.connect();
    try {
      await client.query("SELECT pg_advisory_lock(4398)");
      try {
        await client.query(POSTGRES_SCHEMA);
      } finally {
        await client.query("SELECT pg_advisory_unlock(4398)");
      }
    } finally {
      client.release();
    }
  })();
  ready.catch(() => {}); // surfaced by whoever awaits it (server.js, first query)

  const api = bind(pool);
  const whenReady = (fn) => async (...args) => {
    await ready;
    return fn(...args);
  };

  return {
    dialect: "postgres",
    get: whenReady(api.get),
    all: whenReady(api.all),
    run: whenReady(api.run),
    insert: whenReady(api.insert),
    async transaction(fn) {
      await ready;
      const client = await pool.connect();
      try {
        await client.query("BEGIN");
        const out = await fn(bind(client));
        await client.query("COMMIT");
        return out;
      } catch (err) {
        await client.query("ROLLBACK").catch(() => {});
        throw err;
      } finally {
        client.release();
      }
    },
    isUniqueViolation: (err) => Boolean(err) && err.code === "23505",
    ready,
    async close() {
      await pool.end();
    },
    raw: pool,
  };
}

const db = config.databaseUrl ? createPostgres() : createSqlite();

/** A short description for the startup log, without the password. */
db.describe = () => {
  if (db.dialect === "sqlite") return `SQLite (${config.databasePath})`;
  try {
    const u = new URL(config.databaseUrl);
    return `PostgreSQL (${u.hostname}${u.pathname})`;
  } catch (_) {
    return "PostgreSQL";
  }
};

/** Current time in the format both databases store and return. */
db.now = () => new Date().toISOString();

module.exports = db;
