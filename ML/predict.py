from __future__ import annotations

# Provides command-line and HTTP interfaces for analyzing sandbox reports with ML models.

import sys
import argparse
import json
import hashlib
import io
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from typing import Any

import joblib

from config import DEFAULT_MALICIOUS_THRESHOLD, FEATURE_COLUMNS, FEATURE_SCHEMA_VERSION
from model_utils import reports_to_matrix
from report_parser import analyze_report, load_report


def build_argument_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Analyze JSON reports from an Azure sandboxed environment for malicious traffic signals."
    )
    parser.add_argument(
        "--file",
        type=str,
        help="Path to a JSON report generated by an Azure sandboxed environment. If omitted, reads JSON from stdin.",
    )
    parser.add_argument(
        "--serve",
        action="store_true",
        help="Start an HTTP server that accepts POSTed JSON reports from the Azure sandboxed environment.",
    )
    parser.add_argument("--host", default="127.0.0.1", help="Server host when using --serve.")
    parser.add_argument("--port", type=int, default=8000, help="Server port when using --serve.")
    parser.add_argument(
        "--threshold",
        type=float,
        default=DEFAULT_MALICIOUS_THRESHOLD,
        help="Risk threshold used to label a report as malicious.",
    )
    parser.add_argument("--classifier-model", help="Random Forest .joblib model to use for classification.")
    parser.add_argument("--anomaly-model", help="Isolation Forest .joblib model to use for novelty detection.")
    return parser


def main() -> None:
    parser = build_argument_parser()
    args = parser.parse_args()

    classifier = load_model(args.classifier_model) if args.classifier_model else None
    anomaly_detector = load_model(args.anomaly_model) if args.anomaly_model else None
    if args.serve:
        run_server(args.host, args.port, threshold=args.threshold, classifier=classifier, anomaly_detector=anomaly_detector)
        return

    report = load_input_report(args.file)
    output = predict_report(
        report,
        threshold=args.threshold,
        classifier=classifier,
        anomaly_detector=anomaly_detector,
    )
    print(json.dumps(output, indent=2))


def load_model(path: str | Path) -> Any:
    """Identify the exact trusted artifact loaded, including older estimators."""
    data = Path(path).read_bytes()
    model = joblib.load(io.BytesIO(data))
    model.sentinel_artifact_version_ = "sha256:" + hashlib.sha256(data).hexdigest()
    model_info(model)  # Reject known incompatible schemas before serving.
    return model


def model_info(model: Any) -> dict[str, Any]:
    if model is None:
        return {"loaded": False, "type": None, "version": None,
                "feature_schema_version": None, "schema_verified": False}
    schema = getattr(model, "sentinel_feature_schema_", None)
    if schema is not None and (not isinstance(schema, dict)
            or schema.get("version") != FEATURE_SCHEMA_VERSION
            or schema.get("columns") != FEATURE_COLUMNS):
        raise ValueError("Model feature schema is incompatible with this predictor; retrain the model.")
    count = getattr(model, "n_features_in_", len(FEATURE_COLUMNS))
    if count != len(FEATURE_COLUMNS):
        raise ValueError("Model feature count is incompatible with this predictor.")
    return {"loaded": True, "type": type(model).__name__,
            "version": getattr(model, "sentinel_artifact_version_", None),
            "feature_schema_version": schema["version"] if schema else None,
            "schema_verified": schema is not None}


def scoring_info(threshold: float, classifier: Any, anomaly_detector: Any) -> dict[str, Any]:
    if not 0 <= threshold <= 1:
        raise ValueError("Threshold must be between 0 and 1.")
    return {
        # These sources describe distinct outputs; anomalies never replace the verdict.
        "prediction_source": "trained_model" if classifier is not None else "heuristic",
        "anomaly_source": "trained_model" if anomaly_detector is not None else None,
        "threshold": threshold,
        "feature_schema_version": FEATURE_SCHEMA_VERSION,
        "models": {"classifier": model_info(classifier), "anomaly": model_info(anomaly_detector)},
    }


def predict_report(
    report: dict[str, Any],
    threshold: float = DEFAULT_MALICIOUS_THRESHOLD,
    classifier: Any = None,
    anomaly_detector: Any = None,
) -> dict[str, Any]:
    metadata = scoring_info(threshold, classifier, anomaly_detector)
    heuristic = analyze_report(report, threshold=threshold)
    output = heuristic.to_dict()
    output.update(metadata)

    if classifier is None and anomaly_detector is None:
        return output

    features = reports_to_matrix([report])
    if classifier is not None:
        predicted = int(classifier.predict(features)[0])
        output["classifier_prediction"] = predicted
        if not hasattr(classifier, "predict_proba"):
            raise ValueError("The classifier model does not support predict_proba().")
        probabilities = classifier.predict_proba(features)[0]
        classes = list(getattr(classifier, "classes_", []))
        if 1 not in classes:
            raise ValueError("The classifier model does not provide a malicious class.")
        malicious_probability = float(probabilities[classes.index(1)])
        output["classifier_probability"] = malicious_probability
        output["malicious"] = malicious_probability >= threshold
        output["risk_score"] = round(malicious_probability, 3)
        output["risk_level"] = _risk_level(malicious_probability)

    if anomaly_detector is not None:
        prediction = int(anomaly_detector.predict(features)[0])
        output["anomaly_prediction"] = "anomaly" if prediction == -1 else "known"
        output["anomaly_score"] = float(anomaly_detector.decision_function(features)[0])

    return output


def _risk_level(score: float) -> str:
    if score >= 0.8:
        return "critical"
    if score >= 0.6:
        return "high"
    if score >= 0.4:
        return "medium"
    return "low"


def load_input_report(file_path: str | None) -> dict[str, Any]:
    if file_path:
        return load_report(Path(file_path))

    raw_input = sys.stdin.read().strip()
    if not raw_input:
        raise ValueError("No JSON input received.")
    return load_report(raw_input)


class ReportRequestHandler(BaseHTTPRequestHandler):
    server_version = "AzureSandboxReportAnalyzer/1.0"
    threshold = DEFAULT_MALICIOUS_THRESHOLD
    classifier: Any = None
    anomaly_detector: Any = None

    def do_POST(self) -> None:  # noqa: N802
        if self.path not in {"/analyze", "/analyze-report", "/"}:
            self.send_error(404, "Endpoint not found")
            return

        content_length = int(self.headers.get("Content-Length", "0"))
        body = self.rfile.read(content_length)

        try:
            payload = json.loads(body.decode("utf-8"))
            result = predict_report(
                payload,
                threshold=self.threshold,
                classifier=self.classifier,
                anomaly_detector=self.anomaly_detector,
            )
            response = json.dumps(result).encode("utf-8")
        except Exception as exc:  # pragma: no cover - defensive HTTP boundary
            response = json.dumps({"error": str(exc)}).encode("utf-8")
            self.send_response(400)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(response)))
            self.end_headers()
            self.wfile.write(response)
            return

        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(response)))
        self.end_headers()
        self.wfile.write(response)

    def do_GET(self) -> None:  # noqa: N802
        if self.path in {"/", "/health"}:
            response = json.dumps({"status": "ok", **scoring_info(
                self.threshold, self.classifier, self.anomaly_detector,
            )}).encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(response)))
            self.end_headers()
            self.wfile.write(response)
            return

        self.send_error(404, "Endpoint not found")


def run_server(
    host: str,
    port: int,
    threshold: float = DEFAULT_MALICIOUS_THRESHOLD,
    classifier: Any = None,
    anomaly_detector: Any = None,
) -> None:
    server = create_server(host, port, threshold, classifier, anomaly_detector)
    print(f"Listening on http://{host}:{port}")
    print("POST JSON reports from the Azure sandboxed environment to /analyze or /analyze-report")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


def create_server(
    host: str,
    port: int,
    threshold: float = DEFAULT_MALICIOUS_THRESHOLD,
    classifier: Any = None,
    anomaly_detector: Any = None,
) -> ThreadingHTTPServer:
    scoring_info(threshold, classifier, anomaly_detector)
    handler = type(
        "ConfiguredReportRequestHandler",
        (ReportRequestHandler,),
        {
            "threshold": threshold,
            "classifier": classifier,
            "anomaly_detector": anomaly_detector,
        },
    )
    return ThreadingHTTPServer((host, port), handler)


if __name__ == "__main__":
    main()
